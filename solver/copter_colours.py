"""Private entered-colour solver for the closed-shape Copter action.

The compiled words are generated by this project's whole-region model and
certified offline. They contain no scramble witnesses and need no SymPy at
runtime. A completed colour word is expanded to guarded physical turns by
the caller; this module alone does not declare the real puzzle complete.
"""
from collections import Counter
from functools import lru_cache
from pathlib import Path
import json,zlib
from cube.copter_aligned import AlignedCopter,generators,source_key
from cube.polyhedral import Move,dot,cross
from solver.polyhedral import simplify,inverse_word,_parity
from solver.lattice_data import geometry_key

ASSET=Path(__file__).resolve().parent/'data/curvy_copter_colour_group.bin'


@lru_cache(maxsize=1)
def prepared():
    data=json.loads(zlib.decompress(ASSET.read_bytes()));cube=AlignedCopter()
    macros=[[[m.axis,m.layer,m.amount] for m in word] for action,word in generators()]
    if (data.get('version')!=1 or data.get('geometry')!=geometry_key(cube.geometry) or data.get('source')!=source_key()
            or data.get('macros')!=macros or sorted(data.get('base',()))!=list(range(72))):
        raise ValueError('Copter colour data do not match the guarded model')
    rows=tuple(tuple((int(beta),tuple(record['permutation']),tuple(Move(*m) for m in record['word']))
                     for beta,record in row.items()) for row in data['transversals'])
    if len(rows)!=72:raise ValueError('Incomplete Copter colour table')
    return tuple(data['base']),rows


def validate(colors):
    cube=AlignedCopter(colors);g=cube.geometry;goal=[s.face for s in g.stickers]
    if any(type(c) is not int or c not in range(6) for c in colors):raise ValueError('Please enter every sticker')
    if Counter(colors)!=Counter(goal):raise ValueError('The color counts do not match this puzzle')
    # A leaf may travel between all 24 slots; two-colour edge carriers remain
    # individually anchored. Corners have unique three-colour combinations.
    corners=[];expected=[];corner_slots=[];flips=0
    for slots in g.pieces:
        if len(slots)==1:continue
        painted=tuple(sorted(colors[s] for s in slots));home=tuple(sorted(goal[s] for s in slots))
        if len(slots)==2:
            if painted!=home:raise ValueError('A piece has an impossible color combination or position')
            flips+=colors[slots[0]]!=goal[slots[0]]
        else:corners.append(painted);expected.append(home);corner_slots.append(slots)
    if Counter(corners)!=Counter(expected):raise ValueError('A piece has an impossible color combination or position')
    def ordered(slots):
        out=sorted(slots,key=lambda i:goal[i]);normals=[g.spec.normals[goal[i]] for i in out]
        if dot(cross(normals[0],normals[1]),normals[2])<0:out[1],out[2]=out[2],out[1]
        return out
    home_cycles=[tuple(goal[i] for i in ordered(slots)) for slots in corner_slots]
    destinations=[];twists=0
    for slots in corner_slots:
        paint=tuple(colors[i] for i in ordered(slots))
        home=next(i for i,cycle in enumerate(home_cycles) if sorted(cycle)==sorted(paint))
        cycle=home_cycles[home];destinations.append(home)
        if not any(paint==cycle[shift:]+cycle[:shift] for shift in range(3)):
            raise ValueError('A piece has a mirrored or impossible orientation')
        twists+=paint.index(cycle[0])
    # Certified order is (24!/2) * 3^7 * 8! * 2^11, with the edge parity
    # character tied to S8. Four indistinguishable leaves per colour
    # absorb leaf-label parity, so it is not an additional input restriction.
    if twists%3 or _parity(destinations)!=flips%2:
        raise ValueError('The entered pieces violate an orientation or permutation constraint')
    return cube


def solve(colors,cancel=None,progress=None):
    if cancel and cancel():raise InterruptedError()
    cube=validate(tuple(colors));start=tuple(cube.colors);goal=tuple(s.face for s in cube.geometry.stickers)
    if start==goal:return ()
    base,rows=prepared();seen=set();nodes=0
    def choices(level,current):
        if current==goal:return iter((None,))
        if level==len(base) or (level,current) in seen:return iter(())
        seen.add((level,current));k=base[level];options=[]
        for beta,permutation,word in rows[level]:
            if current[beta]!=goal[k]:continue
            child=tuple(current[i] for i in permutation)
            options.append((sum(a!=b for a,b in zip(child,goal)),len(word),beta,child,word))
        options.sort(key=lambda row:row[:3]);return iter(options)
    factors=[];stack=[(0,start,choices(0,start))];found=None
    while stack:
        if cancel and cancel():raise InterruptedError()
        level,current,options=stack[-1];item=next(options,False)
        if item is None:found=tuple(factors);break
        if item is False:
            stack.pop()
            if factors:factors.pop()
            continue
        _,_,_,child,word=item;factors.append(word);nodes+=1
        stack.append((level+1,child,choices(level+1,child)))
        if progress and nodes%128==0:progress(-1,0)
    if found is None:raise ValueError('The entered puzzle is not a legal state')
    result=simplify(tuple(move for word in found for move in inverse_word(word,2)),2)
    replay=cube.entered()
    for move in result:
        if cancel and cancel():raise InterruptedError()
        replay.apply_move(move)
    if not replay.is_solved():raise ValueError('Copter colour solution replay failed')
    return result
