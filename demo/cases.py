def inverse_move_str(move: str) -> str:
    label, is_wide, count = parse_move_str(move)
    base = label.lower() if is_wide else label
    return base + suffix_for_count((4 - count) % 4)


def inverse_moves(moves):
    inv = []
    for m in reversed(list(moves)):
        inv.append(inverse_move_str(m))
    return inv


def build_before(cube_factory, moves):
    cube = cube_factory()
    for m in inverse_moves(moves):
        cube.apply_move(m)
    return cube


